import { chromium } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
await mkdir('screenshots', { recursive:true })
const browser = await chromium.launch({ headless:true })
const context = await browser.newContext({ viewport:{ width:1440, height:1000 }, deviceScaleFactor:1 })
const page = await context.newPage()
const errors = []
page.on('pageerror', error => errors.push(error.message))
await page.goto('http://127.0.0.1:3000/', { waitUntil:'networkidle' })
await page.waitForTimeout(2600)
await page.screenshot({ path:'screenshots/landing-desktop.png', fullPage:true })
await page.goto('http://127.0.0.1:3000/upload', { waitUntil:'networkidle' })
await page.waitForTimeout(900)
await page.screenshot({ path:'screenshots/uploader-desktop.png', fullPage:true })
await page.setViewportSize({ width:390, height:844 })
await page.goto('http://127.0.0.1:3000/', { waitUntil:'networkidle' })
await page.waitForTimeout(3200)
await page.screenshot({ path:'screenshots/landing-mobile.png', fullPage:true })
await page.goto('http://127.0.0.1:3000/upload', { waitUntil:'networkidle' })
await page.waitForTimeout(800)
await page.screenshot({ path:'screenshots/uploader-mobile.png', fullPage:true })
await page.setViewportSize({ width:1440, height:1000 })
await page.goto('http://127.0.0.1:3000/upload', { waitUntil:'networkidle' })
await page.locator('.legacy-provider').filter({ hasText:'Sohu' }).click()
const uploadResponse = page.waitForResponse(response => response.url().includes('/api/upload') && response.request().method() === 'POST', { timeout:90000 })
await page.locator('.legacy-native-input').setInputFiles('public/upload-illustration.png')
const response = await uploadResponse
if (!response.ok()) throw new Error(`Real Sohu upload failed: ${await response.text()}`)
await page.locator('.file-item').waitFor({ state:'visible' })
await page.waitForTimeout(600)
await page.screenshot({ path:'screenshots/uploader-success.png', fullPage:true })
console.log('Real Sohu upload screenshot captured')
console.log(JSON.stringify({ screenshots:4, pageErrors:errors }, null, 2))
await browser.close()
